export function makeT(uiLanguage) {
  const table = STRINGS[uiLanguage] || STRINGS.en;
  // Falls back to English rather than showing a key, so a missing translation
  // degrades to a readable string instead of "studyDeck".
  return (key) => table[key] ?? STRINGS.en[key] ?? key;
}

